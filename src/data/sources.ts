export const SOURCE_BY_ID: Record<string, Source> = Object.fromEntries(SOURCES.map((s) => [s.id, s]));

export function sourceLabel(id: string): string {
  const s = SOURCE_BY_ID[id];
  if (!s) return id;
  const first = s.authors.split(',')[0].replace(/ [A-Z]{1,3}$/, '');
  return `${first} ${s.year}`;
}

/** Les revues narratives, articles fondateurs et recommandations relèvent du consensus (B), pas de la preuve (A). */
export function sourceLevel(s: Source): Level {
  return s.type === 'Revue narrative' || s.type === 'Article fondateur' || s.type === 'Recommandation' ? 'B' : 'A';
}
